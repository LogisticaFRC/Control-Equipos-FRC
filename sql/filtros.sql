-- 1) LISTA DE PRECIOS: un precio por código + proveedor (comparativo)
CREATE TABLE IF NOT EXISTS public.bd_filtros_precios (
  id           bigserial PRIMARY KEY,
  codigo       text NOT NULL,
  marca        text NOT NULL DEFAULT '',   -- marca del FILTRO (BALDWIN, DONALDSON...)
  tipo         text NOT NULL DEFAULT '',   -- ACEITE MOTOR, AIRE PRIMARIO...
  proveedor    text NOT NULL,
  precio       numeric NOT NULL DEFAULT 0,
  fecha_precio date,
  created_at   timestamptz DEFAULT now(),
  updated_at   timestamptz DEFAULT now(),
  CONSTRAINT bd_filtros_precios_unico UNIQUE (codigo, proveedor)
);
ALTER TABLE public.bd_filtros_precios ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS bd_filtros_precios_anon_all ON public.bd_filtros_precios;
CREATE POLICY bd_filtros_precios_anon_all ON public.bd_filtros_precios FOR ALL TO anon USING (true) WITH CHECK (true);

-- 2) APLICACIONES: qué código usa cada MARCA + MODELO de equipo (referencia cruzada + cantidad)
CREATE TABLE IF NOT EXISTS public.bd_filtros (
  id            bigserial PRIMARY KEY,
  equipo_marca  text NOT NULL DEFAULT '',
  equipo_modelo text NOT NULL DEFAULT '',
  tipo          text NOT NULL DEFAULT '',
  marca         text NOT NULL DEFAULT '',
  codigo        text NOT NULL,
  cantidad      numeric DEFAULT 1,
  ultimo_uso    date,
  ultimo_afi    text,
  created_at    timestamptz DEFAULT now(),
  updated_at    timestamptz DEFAULT now()
);
-- Si bd_filtros se creó con la versión anterior (con proveedor/precio), pasar esos precios a la lista
-- y dejar una sola fila por modelo + tipo + código.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='bd_filtros' AND column_name='proveedor') THEN
    INSERT INTO public.bd_filtros_precios (codigo, marca, tipo, proveedor, precio, fecha_precio)
    SELECT DISTINCT ON (codigo, proveedor) codigo, marca, tipo, proveedor, precio, fecha_precio
      FROM public.bd_filtros WHERE proveedor <> '' AND precio > 0
      ORDER BY codigo, proveedor, fecha_precio DESC NULLS LAST
    ON CONFLICT (codigo, proveedor) DO NOTHING;
    ALTER TABLE public.bd_filtros DROP CONSTRAINT IF EXISTS bd_filtros_unico;
    DELETE FROM public.bd_filtros a USING public.bd_filtros b
      WHERE a.id > b.id AND a.equipo_marca = b.equipo_marca AND a.equipo_modelo = b.equipo_modelo
        AND a.tipo = b.tipo AND a.codigo = b.codigo;
    ALTER TABLE public.bd_filtros DROP COLUMN IF EXISTS proveedor;
    ALTER TABLE public.bd_filtros DROP COLUMN IF EXISTS precio;
    ALTER TABLE public.bd_filtros DROP COLUMN IF EXISTS fecha_precio;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'bd_filtros_aplicacion_unica') THEN
    ALTER TABLE public.bd_filtros ADD CONSTRAINT bd_filtros_aplicacion_unica UNIQUE (equipo_marca, equipo_modelo, tipo, codigo);
  END IF;
END $$;
